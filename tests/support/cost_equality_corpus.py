def _frame(payload: dict[str, Any]) -> str:
    return f"event: {payload['type']}\ndata: {json.dumps(payload)}"


def capture_frames(
    family: str, split: Any, usage: tuple[int, int, int, int], model: str
) -> list[str]:
    """The SSE frames one finished stream of this family carries."""

    tokens_in, cache_read, cache_write, tokens_out = usage
    counters: dict[str, Any] = {
        "input_tokens": tokens_in,
        "cache_read_input_tokens": cache_read,
        "cache_creation_input_tokens": cache_write,
    }
    if split is not None:
        counters["cache_creation"] = split
    if family == "chat_translated":
        start_usage: dict[str, Any] = {"input_tokens": 999, "output_tokens": 0}
        delta_usage: dict[str, Any] = {**counters, "output_tokens": tokens_out}
        delta_usage.pop("cache_creation", None)
    elif family == "anthropic_cumulative_delta":
        start_usage = {**counters, "output_tokens": 1}
        delta_usage = {**counters, "output_tokens": tokens_out}
    else:
        start_usage = {**counters, "output_tokens": 1}
        delta_usage = {"output_tokens": tokens_out}
    return [
        _frame(
            {
                "type": "message_start",
                "message": {
                    "id": "msg_corpus",
                    "type": "message",
                    "role": "assistant",
                    "model": model,
                    "content": [],
                    "usage": start_usage,
                },
            }
        ),
        _frame(
            {
                "type": "message_delta",
                "delta": {"stop_reason": "end_turn"},
                "usage": delta_usage,
            }
        ),
        _frame({"type": "message_stop"}),
    ]


def capture_cases() -> Iterator[
    tuple[str, str, Any, tuple[int, int, int, int], str, str, bool]
]:
    """``(key, family, split, usage, provider, model, litellm)`` for every capture row."""

    for family in ("anthropic_native", "anthropic_cumulative_delta", "chat_translated"):
        splits = ("absent",) if family == "chat_translated" else tuple(SPLITS)
        for split_name in splits:
            for usage_index, usage in enumerate(CAPTURE_USAGES):
                for provider, model in CAPTURE_ROUTES:
                    for litellm in (False, True):
                        key = (
                            f"{family}|{split_name}|u{usage_index}|{provider}/{model}"
                            f"|litellm={int(litellm)}"
                        )
                        yield (
                            key,
                            family,
                            SPLITS[split_name](usage[2]),
                            usage,
                            provider,
                            model,
                            litellm,
                        )


def capture_records(
    store: Any, make_capture: Callable[[str, bool], Any]
) -> dict[str, dict[str, Any]]:
    """Finish one capture per case on ``store`` and read every stored row back."""

    keys: dict[str, str] = {}
    for number, (key, family, split, usage, provider, model, litellm) in enumerate(
        capture_cases()
    ):
        request_id = f"corpus-{number:05d}"
        keys[request_id] = key
        capture = make_capture(request_id, litellm)
        capture._record.provider = provider
        capture._record.resolved_model = model
        for frame in capture_frames(family, split, usage, model):
            capture._parse_frame(frame)
        capture._finalize("success")
    store.close()
    found: dict[str, dict[str, Any]] = {}
    for request_id, key in keys.items():
        row = store.get_request(request_id)
        assert row is not None, key
        found[key] = {
            name: (
                None
                if row.get(name) is None
                else float(row[name]).hex()
                if name == "cost_usd"
                else row[name]
            )
            for name in CAPTURE_FIELDS
        }
    return found
