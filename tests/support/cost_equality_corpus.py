def routes() -> list[tuple[str | None, str | None]]:
    """Every (provider, model) the pricing corpus walks, deterministically."""

    index = json.loads(MODELS_DEV_FIXTURE.read_text(encoding="utf-8"))
    crossed: list[str] = []
    for bucket in _CROSSED_BUCKETS:
        for model_id in index.get(bucket, {}).get("models", {}):
            if model_id not in crossed:
                crossed.append(model_id)
    found: list[tuple[str | None, str | None]] = [
        (provider, model) for provider in MCC_PROVIDERS for model in crossed
    ]
    for bucket_id in sorted(index):
        for model_id in list(index[bucket_id].get("models", {}))[:2]:
            if (bucket_id, model_id) not in found:
                found.append((bucket_id, model_id))
    found.extend([(None, None), ("anthropic", None), (None, "claude-sonnet-5")])
    return found


def usage_grid() -> Iterator[Usage]:
    """``(tokens_in, tokens_out, cache_read, cache_write, reasoning)``, every combination."""

    for tokens_in in _TOKENS_IN:
        for tokens_out in _TOKENS_OUT:
            for cache_read in _CACHE_READ:
                for cache_write in _CACHE_WRITE:
                    for reasoning in _REASONING:
                        yield (
                            tokens_in,
                            tokens_out,
                            cache_read,
                            cache_write,
                            reasoning,
                        )


def _answer(cost: float | None, source: str | None) -> str:
    return f"{'-' if cost is None else float(cost).hex()}|{source or '-'}"


def _digest(parts: list[str]) -> str:
    return hashlib.sha256("\n".join(parts).encode("utf-8")).hexdigest()[:32]


def route_key(provider: str | None, model: str | None, litellm: bool) -> str:
    return f"{provider or '~'}/{model or '~'}|litellm={int(litellm)}"


def price_digests(price: PriceFn) -> dict[str, str]:
    """One digest per (route, LiteLLM on/off) over the whole usage x mode grid."""

    grid = list(usage_grid())
    digests: dict[str, str] = {}
    for provider, model in routes():
        for litellm in (False, True):
            parts = [
                _answer(*price(provider, model, usage, reported, mode, litellm))
                for usage in grid
                for mode, reported in _MODES
            ]
            digests[route_key(provider, model, litellm)] = _digest(parts)
    return digests


def backfill_digests(
    make_pricer: Callable[[bool], Any],
) -> dict[str, str]:
    """The historical backfill pricer over the same routes and write counts."""

    grid = list(usage_grid())
    digests: dict[str, str] = {}
    for litellm in (False, True):
        pricer = make_pricer(litellm)
        for provider, model in routes():
            parts = [
                _answer(
                    *pricer(provider, model, usage[0], usage[1], usage[2], usage[3])
                )
                for usage in grid
                if usage[4] is None
            ]
            digests[route_key(provider, model, litellm)] = _digest(parts)
    return digests


