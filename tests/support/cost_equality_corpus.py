type Usage = tuple[int | None, int | None, int | None, int | None, int | None]
type PriceFn = Callable[
    [str | None, str | None, Usage, float | None, str, bool],
    tuple[float | None, str | None],
]


def write_catalogues(config_dir: Path) -> None:
    """Write the three caches the readers load, under ``<config_dir>/cache``."""

    cache = config_dir / "cache"
    cache.mkdir(parents=True, exist_ok=True)
    now = datetime.now(UTC).isoformat()
    index = json.loads(MODELS_DEV_FIXTURE.read_text(encoding="utf-8"))
    (cache / "models-dev.json").write_text(
        json.dumps({"fetched_at": now, "index": index}), encoding="utf-8"
    )
    (cache / "litellm-prices.json").write_text(
        json.dumps({"fetched_at": now, "index": LITELLM_INDEX}), encoding="utf-8"
    )
    live = json.loads(OPENROUTER_LIVE_FIXTURE.read_text(encoding="utf-8"))
    rows = []
    for row in live["data"]:
        copied = json.loads(json.dumps(row))
        if copied.get("id") == LIVE_ONE_HOUR_SLUG:
            copied.setdefault("pricing", {})["input_cache_write_1h"] = (
                LIVE_ONE_HOUR_PRICE
            )
        rows.append(copied)
    (cache / "openrouter-models.json").write_text(
        json.dumps({"fetched_at": now, "data": rows}), encoding="utf-8"
    )
    stamp = datetime.now(UTC).timestamp()
    for name in ("models-dev.json", "litellm-prices.json", "openrouter-models.json"):
        os.utime(cache / name, (stamp, stamp))


def patched_config_dir(stack: ExitStack, config_dir: Path) -> None:
    """Point every catalogue reader at ``config_dir`` for the life of ``stack``."""

    for module in (models_dev, litellm_prices, openrouter_catalogue):
        stack.enter_context(
            mock.patch.object(module, "config_dir_path", lambda: config_dir)
        )
