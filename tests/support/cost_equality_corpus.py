"""The pricing corpus the 7.111.0 cost-equality contract replays.

``tests/contracts/test_cost_write_split_equality.py`` prices this corpus and
compares every answer to ``cost_write_split_equality_baseline.json``, which was
generated by this same module on the 7.110.0 tree (``record_baseline``). So the
module may use only what 7.110.0 already had: the real models.dev, LiteLLM and
OpenRouter-live readers over the repo's own trimmed catalogues
(``metadata_ladder_models_dev.json``, ``metadata_ladder_openrouter_live.json``)
plus one LiteLLM map written here, every pricing rung, the historical backfill
pricer, and ``RequestCapture`` fed real Anthropic-shaped SSE frames.

The OpenRouter live list and the LiteLLM map both STATE 1-hour write rates
(invented test numbers), so the 7.110.0 tree reads catalogues that carry them
and ignores them -- which is the point: on the branch, a row that wrote no
1-hour entries must price exactly as it did with those rates present.
"""

