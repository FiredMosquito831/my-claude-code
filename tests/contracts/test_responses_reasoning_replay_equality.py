"""7.58.1 changes the Responses history, and nothing else, byte for byte.

The Responses surface used to replay every earlier thinking block into
``input`` as literal ``<think>`` output text, and the models it serves copied
that format into their answers. 7.58.1 replays no reasoning there. The claim
this file pins is the narrow one the user's rule demands: *only* the two
Responses builders move, and they move by exactly "the thinking is gone".

``responses_reasoning_replay_equality_baseline.json`` was generated by running
:func:`bodies` against a detached worktree at ``f9bff4b0`` (v7.58.0, the
commit this branch forked from). It holds the sha256 of every body's canonical
JSON, and how many ``<think>`` tags v7.58.0 put in each Responses body.

Three statements, per key:

* every non-Responses body -- the Anthropic Messages body and the Chat
  Completions body of every OpenAI-chat profile and standalone client -- is
  byte-identical to v7.58.0;
* every Responses body equals what v7.58.0 built for the *same request with
  its thinking removed* (``|thinking-stripped``): the change is "thinking
  omitted", not a different conversion;
* on a history that carries thinking, v7.58.0's Responses body had ``<think>``
  in it and today's has none.

A diff in the first statement means the equality contract is broken and the
PR must be re-cut. The baseline is not a file to regenerate.
"""

