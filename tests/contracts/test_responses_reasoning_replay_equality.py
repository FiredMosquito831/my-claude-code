RESPONSES_PREFIXES = ("responses/",)
STRIPPED = "|thinking-stripped"


def _payload(fixture: str, *, model: str, strip_thinking: bool) -> dict[str, Any]:
    messages = copy.deepcopy(FIXTURES[fixture])
    if strip_thinking:
        for message in messages:
            message.pop("reasoning_content", None)
            content = message.get("content")
            if message["role"] == "assistant" and isinstance(content, list):
                message["content"] = [
                    block for block in content if block.get("type") != "thinking"
                ]
    return {
        "model": model,
        "max_tokens": 4096,
        "system": "You are a coding agent.",
        "messages": messages,
        "tools": copy.deepcopy(TOOLS),
        "tool_choice": {"type": "auto"},
    }


def _request(
    fixture: str, *, model: str = "provider/a-model", strip_thinking: bool = False
) -> MessagesRequest:
    return MessagesRequest.model_validate(
        _payload(fixture, model=model, strip_thinking=strip_thinking)
    )


def _chat_profiles() -> dict[str, Any]:
    import importlib

    profiles: dict[str, Any] = dict(OPENAI_CHAT_PROFILES)
    for module_name in STANDALONE_PROFILE_MODULES:
        module = importlib.import_module(
            f"my_claude_code.providers.{module_name}.client"
        )
        profiles[f"{module_name}(standalone)"] = module._PROFILE
    return profiles


def _opencode_responses_body(
    provider_id: str, request: MessagesRequest, policy: ReasoningPolicy
) -> dict[str, Any]:
    provider = create_openai_chat_provider(
        provider_id,
        ProviderConfig(api_key="sk-test", base_url="https://opencode.ai/zen/v1"),
        passthrough_rate_limiter(),
        profile=OPENAI_CHAT_PROFILES[provider_id],
    )
    body, _headers = provider._responses.build_body(
        request,
        reasoning=policy,
        max_output_tokens=request.max_tokens,
        extra_body=provider._responses_extra_body(request),
    )
    # The session id behind the cache key is a per-process fingerprint, not
    # a property of the conversion; it is the one field not compared.
    body.pop("prompt_cache_key", None)
    return body


def _responses_bodies(
    fixture: str, policy_name: str, *, strip_thinking: bool
) -> dict[str, Any]:
    policy = POLICIES[policy_name]
    suffix = STRIPPED if strip_thinking else ""
    out: dict[str, Any] = {}
    out[f"responses/chatgpt_oauth/{fixture}/{policy_name}{suffix}"] = (
        build_chatgpt_oauth_request_body(
            _request(fixture, model="gpt-5.6-terra", strip_thinking=strip_thinking),
            reasoning=policy,
        )
    )
    for provider_id, model in (
        ("opencode", "muse-spark-1.3-contributor-free"),
        ("opencode", "a-paid-model"),
        ("opencode_go", "a-go-model"),
    ):
        out[f"responses/{provider_id}:{model}/{fixture}/{policy_name}{suffix}"] = (
            _opencode_responses_body(
                provider_id,
                _request(fixture, model=model, strip_thinking=strip_thinking),
                policy,
            )
        )
    return out


def bodies() -> dict[str, Any]:
    """Every body this contract pins, keyed ``family/…/fixture/policy``."""

    out: dict[str, Any] = {}
    profiles = _chat_profiles()
    no_overrides = ModelParameterOverrides()
    for fixture in sorted(FIXTURES):
        for policy_name in sorted(POLICIES):
            policy = POLICIES[policy_name]
            out[f"anthropic_messages/{fixture}/{policy_name}"] = (
                build_anthropic_messages_body(_request(fixture), reasoning=policy)
            )
            for name in sorted(profiles):
                profile = profiles[name]
                out[f"openai_chat/{name}/{fixture}/{policy_name}"] = (
                    build_openai_chat_request_body(
                        _request(fixture),
                        reasoning=policy,
                        policy=profile.request_policy,
                        postprocessors=profile.request_postprocessors,
                        provider_id=name,
                        overrides=no_overrides,
                    )
                )
            out.update(_responses_bodies(fixture, policy_name, strip_thinking=False))
            out.update(_responses_bodies(fixture, policy_name, strip_thinking=True))
    return out


def canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, indent=1, default=str)


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value).encode("utf-8")).hexdigest()


def snapshot() -> dict[str, Any]:
    """What the baseline file stores: every body's digest, and how many
    ``<think>`` tags each Responses body carried."""

    built = bodies()
    return {
        "digests": {key: digest(value) for key, value in sorted(built.items())},
        "think_tags": {
            key: canonical(value).count("<think>")
            for key, value in sorted(built.items())
            if key.startswith(RESPONSES_PREFIXES)
        },
    }


BASELINE: dict[str, Any] = (
    json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    if BASELINE_PATH.exists()
    else {"digests": {}, "think_tags": {}}
)
DIGESTS: dict[str, str] = BASELINE["digests"]
THINK_TAGS_BEFORE: dict[str, int] = BASELINE["think_tags"]


@functools.cache
def _now() -> dict[str, Any]:
    """Built once, inside the first test -- under the suite's hermetic home."""

    return bodies()


def _has_thinking(fixture: str) -> bool:
    for message in FIXTURES[fixture]:
        if message.get("reasoning_content"):
            return True
        content = message.get("content")
        if isinstance(content, list) and any(
            block.get("type") == "thinking" for block in content
        ):
            return True
    return False


def test_the_snapshot_covers_every_family_fixture_and_policy() -> None:
    """A snapshot that quietly stopped covering something proves nothing."""

    assert set(_now()) == set(DIGESTS)
    families = {key.split("/", 1)[0] for key in _now()}
    assert families == {"anthropic_messages", "openai_chat", "responses"}
    chat_profiles = {
        key.split("/")[1] for key in _now() if key.startswith("openai_chat/")
    }
    assert len(chat_profiles) >= len(OPENAI_CHAT_PROFILES) + len(
        STANDALONE_PROFILE_MODULES
    )


NON_RESPONSES = sorted(key for key in DIGESTS if not key.startswith(RESPONSES_PREFIXES))
RESPONSES = sorted(
    key for key in DIGESTS if key.startswith(RESPONSES_PREFIXES) and STRIPPED not in key
)


@pytest.mark.parametrize("key", NON_RESPONSES)
def test_every_other_surface_is_byte_identical_to_v7_58_0(key: str) -> None:
    assert digest(_now()[key]) == DIGESTS[key]


@pytest.mark.parametrize("key", RESPONSES)
def test_a_responses_body_is_v7_58_0_with_the_thinking_left_out(key: str) -> None:
    assert digest(_now()[key]) == DIGESTS[key + STRIPPED]
    assert digest(_now()[key + STRIPPED]) == DIGESTS[key + STRIPPED], (
        "a history with no thinking must build exactly what v7.58.0 built"
    )


@pytest.mark.parametrize("key", RESPONSES)
def test_v7_58_0_replayed_think_tags_and_this_release_does_not(key: str) -> None:
    fixture = key.split("/")[2]
    assert "<think>" not in canonical(_now()[key])
    if _has_thinking(fixture):
        assert THINK_TAGS_BEFORE[key] > 0
        assert digest(_now()[key]) != DIGESTS[key]
    else:
        assert THINK_TAGS_BEFORE[key] == 0
        assert digest(_now()[key]) == DIGESTS[key]
