"""7.102.1 moves no Anthropic Messages body that carries no foreign thinking.

7.102.1 drops, from the outbound copy, the thinking blocks Anthropic did not
write (an absent or blank ``signature``, or ``redacted_thinking`` wrapping
JSON). The user's rule is that a request with no such block goes out exactly
as before. This file pins that, byte for byte, over every body shape the
builder serves:

* every history of ``test_responses_reasoning_replay_equality`` -- all of its
  thinking is signed ``sig-N`` and its ``redacted_thinking`` is opaque, so
  none of it is foreign -- plus the shapes that contract never needed: Anthropic
  ciphertext, ``cache_control`` everywhere it is legal, server tools,
  documents, an inline system turn, an assistant turn that arrived empty,
  consecutive turns of one role, a trailing assistant prefill, a non-blank
  signature that is not Anthropic's, and plain strings;
* under every reasoning policy routing can hand the builder, and every
  ``thinking`` object a client can send (none, adaptive, manual, disabled).

``anthropic_foreign_thinking_equality_baseline.json`` was generated by running
:func:`snapshot` against a detached worktree at ``0390fffd`` (v7.102.0, the
commit this branch forked from). It holds the sha256 of each body's bytes in
the order the HTTP client serialises them (insertion order, not sorted), so a
reordered key is a diff too. The baseline is not a file to regenerate: a
mismatch means the equality contract is broken.

``wire_without_thinking_enabled`` is the same digest with MCC's own
``thinking.enabled`` default removed, recorded at the same commit for the
bodies where that key was on the wire -- the one difference the next PATCH
(bug B) is allowed to make.
"""

