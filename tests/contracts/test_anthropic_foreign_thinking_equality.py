def _payload(fixture: str, client_thinking: str) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "model": "claude-haiku-5-5",
        "max_tokens": 16000,
        "system": [
            {
                "type": "text",
                "text": "You are a coding agent.",
                "cache_control": _EPHEMERAL,
            }
        ],
        "messages": copy.deepcopy(FIXTURES[fixture]),
        "tools": copy.deepcopy(TOOLS),
        "tool_choice": {"type": "auto"},
        "metadata": {"user_id": "user_0123"},
    }
    thinking = CLIENT_THINKING[client_thinking]
    if thinking is not None:
        payload["thinking"] = copy.deepcopy(thinking)
    return payload


def corpus() -> dict[str, tuple[MessagesRequest, ReasoningPolicy]]:
    """Every request this contract builds, keyed ``fixture/policy/thinking``."""

    out: dict[str, tuple[MessagesRequest, ReasoningPolicy]] = {}
    for fixture in sorted(FIXTURES):
        for policy_name in sorted(POLICIES):
            for thinking in sorted(CLIENT_THINKING):
                out[f"{fixture}/{policy_name}/{thinking}"] = (
                    MessagesRequest.model_validate(_payload(fixture, thinking)),
                    POLICIES[policy_name],
                )
    return out


def bodies() -> dict[str, dict[str, Any]]:
    return {
        key: build_anthropic_messages_body(request, reasoning=policy)
        for key, (request, policy) in corpus().items()
    }


def wire_bytes(body: Any) -> bytes:
    """The body as the HTTP client puts it on the wire: insertion order."""

    return json.dumps(
        body, ensure_ascii=False, separators=(",", ":"), allow_nan=False
    ).encode("utf-8")


def digest(body: Any) -> str:
    return hashlib.sha256(wire_bytes(body)).hexdigest()


def without_thinking_enabled(body: dict[str, Any]) -> dict[str, Any]:
    """The body with MCC's own ``thinking.enabled`` default removed, if present."""

    thinking = body.get("thinking")
    if not isinstance(thinking, dict) or "enabled" not in thinking:
        return body
    return {
        **body,
        "thinking": {key: value for key, value in thinking.items() if key != "enabled"},
    }


def snapshot() -> dict[str, Any]:
    """What the baseline file stores."""

    built = bodies()
    return {
        "wire": {key: digest(body) for key, body in sorted(built.items())},
        "wire_without_thinking_enabled": {
            key: digest(without_thinking_enabled(body))
            for key, body in sorted(built.items())
            if without_thinking_enabled(body) is not body
        },
    }


def _baseline() -> dict[str, Any]:
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


def test_the_baseline_covers_exactly_this_corpus() -> None:
    assert sorted(_baseline()["wire"]) == sorted(corpus())


def test_no_body_without_foreign_thinking_moves_by_a_byte() -> None:
    baseline = _baseline()["wire"]
    moved = [
        key for key, body in sorted(bodies().items()) if digest(body) != baseline[key]
    ]

    assert moved == []


def test_the_corpus_holds_nothing_foreign_and_records_no_note() -> None:
    for key, (request, policy) in sorted(corpus().items()):
        notes: dict[str, str] = {}
        body = build_anthropic_messages_body(
            request, reasoning=policy, wire_notes=notes
        )
        assert notes == {}, key
        assert len(body["messages"]) == len(request.messages), key
