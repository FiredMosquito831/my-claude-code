def _parse(provider_id: str, spec: dict[str, Any]) -> frozenset[ProviderModelInfo]:
    collection = spec["collection_field"]
    payload = {collection: spec["rows"]}
    if spec["dialect"] == "openrouter":
        return extract_openrouter_tool_model_infos(payload, provider_name=provider_id)
    if spec["dialect"] == "commandcode":
        return extract_commandcode_model_infos(payload, provider_name=provider_id)
    profile = OPENAI_CHAT_PROFILES.get(provider_id)
    listing = profile.model_listing if profile is not None else OpenAIModelListing()
    return extract_openai_model_infos(
        payload,
        provider_name=provider_id,
        collection_field=listing.collection_field,
        id_field=listing.id_field,
        aliases_field=listing.aliases_field,
        required_path_values=listing.required_path_values,
        required_null_field=listing.required_null_field,
        required_sequence_items=listing.required_sequence_items,
        exclude_missing_sequence_fields=listing.exclude_missing_sequence_fields,
        tags_field=listing.tags_field,
        thinking_tag=listing.thinking_tag,
        non_thinking_tag=listing.non_thinking_tag,
        thinking_boolean_path=listing.thinking_boolean_path,
    )


def _document(info: ProviderModelInfo) -> dict[str, Any]:
    document = model_info_document(info)
    document.pop(NEW_DOCUMENT_KEY, None)
    return document


def _canonical_without_declared(info: ProviderModelInfo) -> str:
    text = canonical_model_info(info)
    marker = f",{NEW_DOCUMENT_KEY}="
    return text[: text.rindex(marker)] + ")" if marker in text else text


def _without_new_rows(capabilities: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in capabilities.items() if k not in NEW_CAPABILITY_KEYS}


def _page_without_new_rows(page: dict[str, Any]) -> dict[str, Any]:
    for provider in page["providers"]:
        for model in provider["models"]:
            model["capabilities"] = _without_new_rows(model["capabilities"])
    return page


def _catalogue_route_without_new_rows(body: dict[str, Any]) -> dict[str, Any]:
    for model in body.get("models", []):
        provenance = model.get("provenance") or {}
        for key in NEW_CAPABILITY_KEYS:
            provenance.pop(key, None)
    return body


def _canon(value: Any) -> str:
    return model_metadata._canonical(value)


def snapshot(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> dict[str, Any]:
    """Every output the ladder produced before 7.79.0, from the committed rows."""

    monkeypatch.setenv("MCC_CONFIG_DIR", str(tmp_path))
    write_models_dev_cache(json.loads(MODELS_DEV_PATH.read_text(encoding="utf-8")))
    cached = read_models_dev_cache()
    assert cached is not None
    rows: dict[str, dict[str, Any]] = json.loads(ROWS_PATH.read_text(encoding="utf-8"))

    out: dict[str, Any] = {}
    catalogues: dict[str, tuple[ProviderModelInfo, ...]] = {}
    for provider_id in sorted(rows):
        parsed = sorted(
            _parse(provider_id, rows[provider_id]), key=lambda i: i.model_id
        )
        enriched = enrich_model_infos(parsed, cached.index, provider_id)
        catalogues[provider_id] = tuple(enriched)
        out[f"records/{provider_id}/parsed"] = [_document(info) for info in parsed]
        out[f"records/{provider_id}/enriched"] = [_document(info) for info in enriched]
        out[f"canonical/{provider_id}"] = [
            _canonical_without_declared(info) for info in enriched
        ]
        for info in enriched:
            out[f"capabilities/{provider_id}/{info.model_id}"] = _without_new_rows(
                capability_payload(provider_id, info.model_id, info)
            )

    first = next(iter(catalogues["open_router"]))
    settings = Settings.model_validate(
        {**FAKE_KEYS, "MODEL": f"open_router/{first.model_id}"}
    )
    app = create_test_app(settings)
    manager = provider_manager_for_app(app)
    for provider_id, infos in catalogues.items():
        manager.cache_model_infos(provider_id, infos)

    for provider_id, infos in catalogues.items():
        for info in infos:
            model_id = info.model_id
            ref = f"{provider_id}/{model_id}"
            out[f"routing/{ref}"] = {
                "output_limit": manager.model_output_limit(provider_id, model_id),
                "context_length": manager.model_context_length(provider_id, model_id),
                "reasoning_capability": _canon(
                    manager.model_reasoning_capability(provider_id, model_id)
                ),
                "reasoning_dialect": _canon(
                    manager.model_reasoning_dialect(provider_id, model_id)
                ),
                "vision": manager.cached_model_supports_vision(provider_id, model_id),
                "thinking": manager.cached_model_supports_thinking(
                    provider_id, model_id
                ),
            }
            out[f"prices/{ref}"] = [
                _canon(card)
                for card in rate_cards(provider_id, model_id, litellm_enabled=False)
            ]

    out["page"] = _page_without_new_rows(
        build_models_page_payload(
            manager.cached_prefixed_model_infos(),
            configured_chat_model_refs(settings),
            settings_model_visibility(settings),
            ModelParameterOverrides(),
            dialect_lookup=manager.model_reasoning_dialect,
            measured=None,
            measured_days=REASONING_MEASUREMENT_DAYS,
            learned=None,
            catalogue_refresh=None,
            image_estimates=None,
            media_placements={},
        )
    )
    client = TestClient(app, client=("127.0.0.1", 50000))
    out["v1/models"] = client.get("/v1/models").json()
    out["v1beta/models"] = build_gemini_models_payload(settings, manager)
    out["admin/catalogue-models"] = client.get("/admin/api/catalogue-models").json()
    out["admin/catalogue-models?provenance=1"] = _catalogue_route_without_new_rows(
        client.get("/admin/api/catalogue-models?provenance=1").json()
    )
    models = build_catalogue_models(settings, manager)
    for format_id in sorted(SERIALISERS):
        document, defaulted = serialise(format_id, models)
        out[f"serialiser/{format_id}"] = {
            "document": document,
            "defaulted": defaulted.as_document(),
            "sidecar": serialise_sidecar(format_id, models),
        }
    return out


#: Outputs kept in the baseline as a digest of their encoding rather than whole:
#: each is large and is built from records whose every field is already kept in
#: full above it (the page repeats the capability rows; the catalogue route
#: repeats the serialiser documents). Equal digests are equal bytes.
DIGESTED_PREFIXES = ("page", "admin/", "serialiser/")


def _encoded(value: Any) -> str:
    return json.dumps(value, sort_keys=True, indent=1, default=str, ensure_ascii=True)


def recorded(outputs: dict[str, Any]) -> dict[str, Any]:
    """The snapshot as the baseline file stores it."""

    stored: dict[str, Any] = {}
    for key, value in outputs.items():
        if key.startswith(DIGESTED_PREFIXES):
            encoded = _encoded(value).encode("utf-8")
            stored[key] = {
                "sha256": hashlib.sha256(encoded).hexdigest(),
                "bytes": len(encoded),
            }
        else:
            stored[key] = json.loads(_encoded(value))
    return stored


def test_every_output_is_byte_identical_to_v7_78_10(monkeypatch, tmp_path) -> None:
    baseline: dict[str, Any] = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    current = recorded(snapshot(monkeypatch, tmp_path))

    assert set(current) == set(baseline)
    differing = [
        key
        for key in sorted(baseline)
        if _encoded(current[key]) != _encoded(baseline[key])
    ]
    assert not differing, differing


def test_the_snapshot_covers_every_dialect_and_every_list() -> None:
    """A snapshot that quietly stopped covering something proves nothing."""

    baseline: dict[str, Any] = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    rows: dict[str, Any] = json.loads(ROWS_PATH.read_text(encoding="utf-8"))
    assert {spec["dialect"] for spec in rows.values()} == {
        "openrouter",
        "generic",
        "commandcode",
    }
    for provider_id in rows:
        assert f"records/{provider_id}/enriched" in baseline
    for key in ("page", "v1/models", "v1beta/models", "admin/catalogue-models"):
        assert key in baseline
    assert {key for key in baseline if key.startswith("serialiser/")} == {
        f"serialiser/{format_id}" for format_id in SERIALISERS
    }
    row_count = sum(len(spec["rows"]) for spec in rows.values())
    assert sum(1 for key in baseline if key.startswith("capabilities/")) == row_count


def test_the_rows_really_carry_what_the_reader_keeps() -> None:
    """The fixture would prove nothing if no row stated anything to keep."""

    rows: dict[str, Any] = json.loads(ROWS_PATH.read_text(encoding="utf-8"))
    stated = 0
    for provider_id, spec in rows.items():
        stated += sum(
            1 for info in _parse(provider_id, spec) if info.declared is not None
        )
    assert stated >= 12
