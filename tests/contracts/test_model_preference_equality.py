"""With no preference set, the wire is byte-identical to 7.24.0.

The overriding constraint on this feature (user, 2026-09-18): everything new
is opt-in, and an operator who sets nothing must get exactly the bytes they
got before it shipped. That is not a property any single assertion can state,
so it is stated as a snapshot: ``model_preference_equality_baseline.json`` was
generated by running :func:`bodies` against a detached worktree at
``aaf442fe`` (v7.24.0, the commit this branch forked from) and is compared
byte for byte here.

Four families, each built through its own encoder -- the Anthropic Messages
surface, an OpenAI Chat Completions profile that parses ``reasoning_effort``,
the Responses surface ChatGPT/Codex is served on, and the Google dialect --
across the client shapes that matter: with tools, with reasoning on, and with
the client sending its own ``thinking`` ask. The router's own two seams are
included through ``output_limits``, so a change to either would move a number
here even though no preference was set.

A diff in this file means the equality contract is broken and the PR must be
re-cut. It is not a file to regenerate.
"""

import json
from pathlib import Path
from typing import Any

import pytest

from my_claude_code.application.routing import (
    ModelRouter,
    apply_output_token_budget,
)
from my_claude_code.config.reasoning import ReasoningPreference
from my_claude_code.config.settings import Settings
from my_claude_code.core.anthropic.models import MessagesRequest
from my_claude_code.core.reasoning import ReasoningEffort, ReasoningPolicy
from my_claude_code.providers.anthropic_messages.request import (
    build_anthropic_messages_body,
)
from my_claude_code.providers.google_openai import VertexReasoningEncoder
from my_claude_code.providers.openai_chat.profiles import OPENAI_CHAT_PROFILES
from my_claude_code.providers.openai_chat.request_policy import (
    build_openai_chat_request_body,
)
from my_claude_code.providers.openai_responses.conversion import (
    build_responses_request_body,
)

BASELINE_PATH = Path(__file__).with_name("model_preference_equality_baseline.json")

TOOLS = [
    {
        "name": "read_file",
        "description": "Read a file from disk.",
        "input_schema": {
            "type": "object",
            "properties": {"path": {"type": "string"}},
            "required": ["path"],
        },
    }
]

CLIENT_SHAPES: dict[str, dict[str, Any]] = {
    "bare": {},
    "with_tools": {"tools": TOOLS, "tool_choice": {"type": "auto"}},
    "client_thinking_ask": {
        "thinking": {"type": "enabled", "budget_tokens": 8192},
        "tools": TOOLS,
    },
    "client_effort_high": {"output_config": {"effort": "high"}, "tools": TOOLS},
}

POLICIES: dict[str, ReasoningPolicy] = {
    "off": ReasoningPolicy.off(),
    "on_high": ReasoningPolicy.on(effort=ReasoningEffort.HIGH),
    "client_default": ReasoningPolicy.provider_default(),
}

# One profile that parses an effort field, kept explicit so the snapshot names
# what it covers rather than depending on dictionary order.
EFFORT_PROFILE = "groq"


def _request(shape: str) -> MessagesRequest:
    payload: dict[str, Any] = {
        "model": "provider/a-model",
        "max_tokens": 4096,
        "messages": [{"role": "user", "content": "hello"}],
    }
    payload.update(CLIENT_SHAPES[shape])
    return MessagesRequest.model_validate(payload)


def _routed_settings() -> Settings:
    settings = Settings()
    settings.model = "nvidia_nim/minimaxai/minimax-m3"
    settings.model_fable = None
    settings.model_opus = None
    settings.model_sonnet = None
    settings.model_haiku = None
    settings.reasoning_policy = ReasoningPreference.CLIENT
    settings.reasoning_fable = ReasoningPreference.INHERIT
    settings.reasoning_opus = ReasoningPreference.INHERIT
    settings.reasoning_sonnet = ReasoningPreference.INHERIT
    settings.reasoning_haiku = ReasoningPreference.INHERIT
    return settings


def _router_numbers(shape: str) -> dict[str, Any]:
    """The two numbers this PR's seams could have moved, and did not."""

    router = ModelRouter(
        _routed_settings(),
        output_limit_lookup=lambda _p, _m: 200_000,
        context_length_lookup=lambda _p, _m: 1_000_000,
    )
    request = _request(shape)
    request.model = "claude-sonnet-4"
    routed = apply_output_token_budget(router.resolve_messages_request(request), 1000)
    return {
        "output_limit": routed.output_limits.limit,
        "max_tokens": routed.request.max_tokens,
        "output_widened_from": routed.output_widened_from,
        "reasoning": repr(routed.reasoning),
        "requested_reasoning": repr(routed.requested_reasoning),
    }


def bodies() -> dict[str, Any]:
    """Every body this contract pins, keyed ``family/shape/policy``."""

    out: dict[str, Any] = {}
    for shape in sorted(CLIENT_SHAPES):
        out[f"router/{shape}"] = _router_numbers(shape)
        for policy_name in sorted(POLICIES):
            policy = POLICIES[policy_name]
            request = _request(shape)
            out[f"anthropic_messages/{shape}/{policy_name}"] = (
                build_anthropic_messages_body(request, reasoning=policy)
            )
            out[f"openai_chat/{shape}/{policy_name}"] = build_openai_chat_request_body(
                _request(shape),
                reasoning=policy,
                policy=OPENAI_CHAT_PROFILES[EFFORT_PROFILE].request_policy,
            )
            out[f"openai_responses/{shape}/{policy_name}"] = (
                build_responses_request_body(_request(shape), reasoning=policy)
            )
            google: dict[str, Any] = {"model": "a-model", "messages": []}
            VertexReasoningEncoder().encode(google, policy)
            out[f"google/{shape}/{policy_name}"] = google
    return out


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, indent=2, default=str)


BASELINE: dict[str, Any] = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


def test_the_snapshot_covers_every_family_and_shape() -> None:
    """A snapshot that quietly stopped covering something proves nothing."""

    assert set(bodies()) == set(BASELINE)
    assert len(BASELINE) >= 4 * len(CLIENT_SHAPES) * len(POLICIES)


@pytest.mark.parametrize("key", sorted(BASELINE))
def test_the_wire_is_byte_identical_to_v7_24_0(key: str) -> None:
    assert _canonical(bodies()[key]) == _canonical(BASELINE[key])
