"""7.58.2 changes one thing on the Chat door's way back: a text-written call's name.

``chat_tool_call_sse_equality_baseline.json`` was generated by running
:func:`streams` against the 7.58.1 tree this branch forked from. For every
Chat provider it drives the real ``stream_response`` over a real
``AsyncOpenAI`` client with three recorded-shape answers, and stores the
sha256 of the SSE the client received, after replacing the per-request ids
(``msg_<uuid>``, ``toolu_heuristic_<hex>``) with fixed tokens:

* ``structured`` -- the tools called as structured ``tool_calls`` deltas, by
  their wire names. Must be byte-identical: that path already decoded.
* ``text`` -- a plain answer with no call at all. Must be byte-identical.
* ``written`` -- the same calls written as text (``● <function=…>``). The
  baseline holds 7.58.1's SSE *with the wire names replaced by the client's
  names in the tool_use block starts*, so "identical to that" says: the name
  is the only thing that moved, and nothing else in the stream did.

Outbound bytes are pinned separately and are untouched by this release: the
7.58.1 equality contract (``test_responses_reasoning_replay_equality.py``)
builds every Chat, Messages and Responses body and passes unmodified.
"""

import hashlib
import json
import re
from pathlib import Path
from typing import Any

import httpx
import pytest
from openai import AsyncOpenAI

from my_claude_code.config.nim import NimSettings
from my_claude_code.providers.nvidia_nim import NvidiaNimProvider
from my_claude_code.providers.openai_chat import OPENAI_CHAT_PROFILES
from tests.providers.request_factory import make_messages_request
from tests.providers.sse_replay import _build_provider, _config
from tests.providers.support import passthrough_rate_limiter

BASELINE_PATH = Path(__file__).with_name("chat_tool_call_sse_equality_baseline.json")

LONG_MCP = "mcp__plugin_chrome-devtools-mcp_chrome-devtools__list_console_messages"
DOTTED = "server.tool"
SHORT = "Read"
CLIENT_NAMES = (SHORT, LONG_MCP, DOTTED)

_SUBCLASSED = (
    "cloudflare",
    "deepseek",
    "mistral",
    "open_router",
    "google_openai",
    "nvidia_nim",
)
CHAT_PROVIDERS = tuple(sorted(OPENAI_CHAT_PROFILES)) + _SUBCLASSED
KINDS = ("structured", "text", "written")

_SCHEMA = {
    "type": "object",
    "properties": {"path": {"type": "string"}},
    "required": ["path"],
}
_MESSAGE_ID = re.compile(r"msg_[0-9a-f-]{36}")
_HEURISTIC_ID = re.compile(r"toolu_heuristic_[0-9a-f]{8}")


def _frame(delta: dict[str, Any], finish: str | None = None) -> str:
    chunk = {
        "id": "chatcmpl-eq",
        "object": "chat.completion.chunk",
        "created": 1757000000,
        "model": "fixture-model",
        "choices": [{"index": 0, "delta": delta, "finish_reason": finish}],
    }
    if finish is not None:
        # Reported usage, as hosts send it: without it the ledger *estimates*
        # output tokens from what it emitted, and a decoded name differs in
        # length from its alias -- a real but separate effect (the estimate
        # counts the name the client now sees), kept out of this comparison.
        chunk["usage"] = {
            "prompt_tokens": 11,
            "completion_tokens": 30,
            "total_tokens": 41,
        }
    return f"data: {json.dumps(chunk)}\n\n"


def _answer(kind: str, wire: list[str]) -> bytes:
    frames = [_frame({"role": "assistant", "content": ""})]
    if kind == "structured":
        for index, name in enumerate(wire):
            frames.append(
                _frame(
                    {
                        "tool_calls": [
                            {
                                "index": index,
                                "id": f"call_{index}",
                                "type": "function",
                                "function": {"name": name, "arguments": ""},
                            }
                        ]
                    }
                )
            )
            frames.extend(
                _frame(
                    {"tool_calls": [{"index": index, "function": {"arguments": piece}}]}
                )
                for piece in ('{"pa', 'th": "a.txt"}')
            )
        frames.append(_frame({}, "tool_calls"))
    elif kind == "written":
        frames.append(_frame({"content": "Working on it.\n"}))
        frames.extend(
            _frame(
                {"content": f"● <function={name}>\n<parameter=path>a.txt</parameter>\n"}
            )
            for name in wire
        )
        frames.append(_frame({}, "stop"))
    else:
        frames.extend(
            _frame({"content": piece}) for piece in ("The answer ", "is 42", ".")
        )
        frames.append(_frame({}, "stop"))
    frames.append("data: [DONE]\n\n")
    return "".join(frames).encode("utf-8")


def _request() -> Any:
    return make_messages_request(
        "fixture-model",
        messages=[{"role": "user", "content": "go"}],
        tools=[
            {"name": name, "description": name, "input_schema": _SCHEMA}
            for name in CLIENT_NAMES
        ],
        thinking={"enabled": False},
        stream=True,
    )


async def stream_once(provider_id: str, kind: str) -> tuple[str, list[str]]:
    """The normalised SSE one provider sends for one answer, and the wire names."""

    provider = (
        NvidiaNimProvider(
            _config(),
            nim_settings=NimSettings(),
            rate_limiter=passthrough_rate_limiter(),
        )
        if provider_id == "nvidia_nim"
        else _build_provider(provider_id)
    )
    wire: list[str] = []

    def handler(http_request: httpx.Request) -> httpx.Response:
        body = json.loads(http_request.content)
        wire.extend(tool["function"]["name"] for tool in body.get("tools", []))
        return httpx.Response(
            200,
            headers={"content-type": "text/event-stream"},
            content=_answer(kind, wire),
            request=http_request,
        )

    provider._client = AsyncOpenAI(
        api_key="test-key",
        base_url=provider._config.base_url,
        max_retries=0,
        http_client=httpx.AsyncClient(transport=httpx.MockTransport(handler)),
    )
    try:
        frames = [
            frame
            async for frame in provider.stream_response(
                _request(), 11, request_id="req-eq"
            )
        ]
    finally:
        await provider.cleanup()
    sse = "".join(frames)
    sse = _MESSAGE_ID.sub("msg_ID", sse)
    sse = _HEURISTIC_ID.sub("toolu_heuristic_ID", sse)
    return sse, wire


def names_decoded(sse: str, wire: list[str]) -> str:
    """``sse`` with each tool_use block start renamed from wire to client name."""

    renamed = dict(zip(wire, CLIENT_NAMES, strict=True))
    out: list[str] = []
    for line in sse.split("\n"):
        if line.startswith("data: ") and '"content_block_start"' in line:
            payload = json.loads(line[len("data: ") :])
            block = payload.get("content_block", {})
            old = block.get("name")
            if block.get("type") == "tool_use" and renamed.get(old, old) != old:
                # The exact JSON spelling of the name, swapped in place, so the
                # rest of the line keeps the ledger's own serialisation.
                line = line.replace(json.dumps(old), json.dumps(renamed[old]), 1)
        out.append(line)
    return "\n".join(out)


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


async def snapshot() -> dict[str, str]:
    """What the baseline stores, built from the tree this runs against."""

    out: dict[str, str] = {}
    for provider_id in CHAT_PROVIDERS:
        for kind in KINDS:
            sse, wire = await stream_once(provider_id, kind)
            if kind == "written":
                sse = names_decoded(sse, wire)
            out[f"{provider_id}/{kind}"] = digest(sse)
    return out


BASELINE: dict[str, str] = (
    json.loads(BASELINE_PATH.read_text(encoding="utf-8"))
    if BASELINE_PATH.exists()
    else {}
)


def test_the_snapshot_covers_every_chat_provider_and_answer() -> None:
    assert set(BASELINE) == {f"{p}/{k}" for p in CHAT_PROVIDERS for k in KINDS}


@pytest.mark.asyncio
@pytest.mark.parametrize("key", sorted(BASELINE))
async def test_only_a_written_calls_name_moved(key: str) -> None:
    provider_id, kind = key.split("/")
    sse, _wire = await stream_once(provider_id, kind)
    assert digest(sse) == BASELINE[key]
